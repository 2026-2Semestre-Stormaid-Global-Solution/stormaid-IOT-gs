CREATE TABLE TB_STORMAID_PASSWORD_RESET (
                                            RESET_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                                            USER_ID NUMBER(19,0) NOT NULL,
                                            CODE_HASH VARCHAR2(255 CHAR) NOT NULL,
                                            EXPIRES_AT TIMESTAMP(6) NOT NULL,
                                            USED NUMBER(1,0) DEFAULT 0 NOT NULL,
                                            CONSTRAINT PK_STORMAID_PASSWORD_RESET PRIMARY KEY (RESET_ID),
                                            CONSTRAINT FK_STORMAID_PASSWORD_USER FOREIGN KEY (USER_ID) REFERENCES TB_STORMAID_USER(USER_ID)
);